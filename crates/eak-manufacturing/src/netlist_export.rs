//! Netlist exports (gap #42): IPC-D-356 for the fabricator's bare-board electrical test, and a
//! generic JSON netlist of the schematic connectivity.
//!
//! The IPC-D-356 file lists every copper pad of the PCB (record 317 for through-hole pads and
//! vias, 327 for surface-mount pads) with its net, position and size in the fixed 80-column
//! layout of the format, in millimetres (`UNITS CUST 1`, 0.001 mm resolution). The
//! coordinates are the PCB's own, as in the Gerber files. Nets come from the footprints' pad
//! nets (set by schematic-to-PCB synchronisation); a pad without a net is written as `N/C`.

use crate::bom_config::natural_cmp;
use eak_core::{PadKind, Project, Side};
use serde_json::json;
use std::collections::BTreeMap;

/// Longest net name the fixed-column net field holds; longer names get an `NNAME` alias.
const NET_FIELD: usize = 14;

/// 0.001 mm units of a length in nanometres.
fn um(nm: i64) -> i64 {
    (nm as f64 / 1_000.0).round() as i64
}

/// Printable ASCII only (anything else becomes `_`), as the fixed-column format needs.
fn field(s: &str) -> String {
    s.chars()
        .map(|c| if c.is_ascii_graphic() { c } else { '_' })
        .collect()
}

/// IPC-D-356 netlist of the PCB. `status` is written as a comment line (for example the
/// DRAFT label of the export).
pub fn ipc_d_356(p: &Project, status: &str) -> String {
    let bottom_access = p.pcb.board.stackup.copper_layers().max(2);
    // Net name aliases for names that do not fit the 14-character field.
    let mut nets: Vec<String> = p
        .pcb
        .footprints
        .values()
        .flat_map(|f| f.pad_nets.values().cloned())
        .chain(p.pcb.vias.values().map(|v| v.net.clone()))
        .filter(|n| !n.is_empty())
        .collect();
    nets.sort();
    nets.dedup();
    let mut alias: BTreeMap<String, String> = BTreeMap::new();
    let mut header_aliases = String::new();
    for n in &nets {
        let f = field(n);
        if f.len() > NET_FIELD || f != *n {
            let a = format!("NNAME{}", alias.len() + 1);
            header_aliases.push_str(&format!("P  {a:<11}{f}\n"));
            alias.insert(n.clone(), a);
        }
    }
    let net_of = |n: Option<&String>| -> String {
        match n.filter(|n| !n.is_empty()) {
            None => "N/C".to_string(),
            Some(n) => alias.get(n).cloned().unwrap_or_else(|| n.clone()),
        }
    };
    let mut out = format!(
        "C  IPC-D-356 netlist generated by eak-manufacturing {}\nC  Project: {} (revision {})\nC  Status: {}\nC  Pads from EAK-IR footprints; vias as 317 records; solder mask coverage is not recorded (S0).\nP  JOB   {}\nP  CODE  00\nP  UNITS CUST 1\nP  DIM   N\n",
        env!("CARGO_PKG_VERSION"),
        field(&p.name),
        p.revision,
        field(status).replace('_', " "),
        field(&p.name),
    );
    out.push_str(&header_aliases);
    let mut fps: Vec<_> = p.pcb.footprints.values().collect();
    fps.sort_by(|a, b| natural_cmp(&a.refdes, &b.refdes));
    for fp in fps {
        let Some(def) = p.library.get(&fp.component_id) else {
            continue;
        };
        for pad in &def.footprint.pads {
            let at = p.pad_position(fp, pad);
            let (w, h) = fp.rotation.apply_size(pad.size_x, pad.size_y);
            let (record, hole, access) = match pad.kind {
                PadKind::Tht => (
                    317,
                    pad.drill
                        .map(|d| format!("D{:04}P", um(d).clamp(0, 9_999)))
                        .unwrap_or_else(|| " ".repeat(6)),
                    0,
                ),
                PadKind::Smd => (
                    327,
                    " ".repeat(6),
                    if fp.side == Side::Top {
                        1
                    } else {
                        bottom_access
                    },
                ),
            };
            out.push_str(&record_line(
                record,
                &net_of(fp.pad_nets.get(&pad.number)),
                &fp.refdes,
                &pad.number,
                &hole,
                access,
                (um(at.x), um(at.y)),
                (um(w), um(h)),
                fp.rotation.degrees(),
            ));
        }
    }
    let mut vias: Vec<_> = p.pcb.vias.values().collect();
    vias.sort_by_key(|v| (v.position.x, v.position.y));
    for v in vias {
        out.push_str(&record_line(
            317,
            &net_of(Some(&v.net)),
            "VIA",
            "",
            &format!("D{:04}P", um(v.drill).clamp(0, 9_999)),
            0,
            (um(v.position.x), um(v.position.y)),
            (um(v.diameter), um(v.diameter)),
            0,
        ));
    }
    out.push_str("999\n");
    out
}

/// One fixed-column test record (columns 1-74 of the 80-column format).
fn record_line(
    record: u32,
    net: &str,
    refdes: &str,
    pin: &str,
    hole: &str,
    access: usize,
    at: (i64, i64),
    size: (i64, i64),
    rotation: u32,
) -> String {
    let (x, y) = (at.0.clamp(-999_999, 999_999), at.1.clamp(-999_999, 999_999));
    let (w, h) = (size.0.clamp(0, 9_999), size.1.clamp(0, 9_999));
    let net = field(net);
    let refdes = field(refdes);
    let pin = field(pin);
    format!(
        "{record:03}{net:<14.14}   {refdes:<6.6}-{pin:<4.4} {hole}A{access:02}X{x:+07}Y{y:+07}X{w:04}Y{h:04}R{rotation:03} S0\n"
    )
}

/// Problems of an IPC-D-356 file written by [`ipc_d_356`] (empty when well formed).
pub fn validate_ipc_d_356(text: &str) -> Vec<String> {
    let mut out = vec![];
    let lines: Vec<&str> = text.lines().collect();
    if lines.last().map(|l| l.trim()) != Some("999") {
        out.push("IPC-D-356 file does not end with the 999 record".into());
    }
    if !lines.iter().any(|l| l.starts_with("P  UNITS")) {
        out.push("IPC-D-356 file has no UNITS parameter".into());
    }
    for (i, l) in lines.iter().enumerate() {
        if l.len() > 80 {
            out.push(format!("line {} is longer than 80 columns", i + 1));
        }
        if (l.starts_with("317") || l.starts_with("327")) && l.len() < 74 {
            out.push(format!("test record on line {} is truncated", i + 1));
        }
    }
    out
}

/// Generic JSON netlist: components and the schematic nets with their pins, plus the PCB pad
/// nets when footprints exist.
pub fn json(p: &Project, status: &str, input_sha256: &str) -> String {
    let nl = eak_engineering::netlist::build(p);
    let mut symbols: Vec<_> = p.schematic.symbols.values().collect();
    symbols.sort_by(|a, b| natural_cmp(&a.refdes, &b.refdes));
    let components: Vec<_> = symbols
        .iter()
        .map(|s| {
            let def = p.library.get(&s.component_id);
            json!({
                "refdes": s.refdes,
                "value": s.value,
                "component_id": s.component_id,
                "footprint": def.map(|d| d.footprint.name.clone()),
                "mpn": def.and_then(|d| d.mpn.clone()),
            })
        })
        .collect();
    let nets: Vec<_> = nl
        .nets
        .values()
        .map(|n| {
            let mut pins: Vec<_> = n.pins.iter().collect();
            pins.sort_by(|a, b| {
                natural_cmp(&a.refdes, &b.refdes).then_with(|| natural_cmp(&a.pin, &b.pin))
            });
            let pins: Vec<_> = pins
                .iter()
                .map(|pin| {
                    json!({
                        "refdes": pin.refdes,
                        "pin": pin.pin,
                        "pin_name": pin.pin_name,
                        "electrical_type": pin.electrical_type,
                    })
                })
                .collect();
            json!({
                "name": n.name,
                "power_port": n.has_power_port,
                "pins": pins,
            })
        })
        .collect();
    let mut fps: Vec<_> = p.pcb.footprints.values().collect();
    fps.sort_by(|a, b| natural_cmp(&a.refdes, &b.refdes));
    let mut pads = vec![];
    for f in fps {
        for (pad, net) in &f.pad_nets {
            pads.push(json!({ "refdes": f.refdes, "pad": pad, "net": net }));
        }
    }
    let doc = json!({
        "format": "eak-netlist",
        "format_version": 1,
        "generator": format!("eak-manufacturing {}", env!("CARGO_PKG_VERSION")),
        "project": p.name,
        "revision": p.revision,
        "input_sha256": input_sha256,
        "status": status,
        "components": components,
        "nets": nets,
        "pcb_pad_nets": pads,
    });
    serde_json::to_string_pretty(&doc).unwrap_or_default()
}

#[cfg(test)]
pub(crate) mod tests {
    use super::*;
    use eak_core::{CopperLayer, FootprintInstance, Point, Rotation, Via};

    /// The BOM test project with every part on the PCB (C1 on the bottom) and one via.
    pub(crate) fn board() -> Project {
        let mut p = crate::bom_config::tests::project();
        let syms: Vec<_> = p.schematic.symbols.values().cloned().collect();
        for (i, s) in syms.iter().enumerate() {
            let mut pad_nets = BTreeMap::new();
            pad_nets.insert("1".to_string(), "VCC_3V3_MAIN_SUPPLY".to_string());
            pad_nets.insert("2".to_string(), "GND".to_string());
            let id = format!("fp_{i}");
            p.pcb.footprints.insert(
                id.clone(),
                FootprintInstance {
                    id,
                    symbol_id: s.id.clone(),
                    component_id: s.component_id.clone(),
                    refdes: s.refdes.clone(),
                    position: Point::mm(5.0 + 5.0 * i as f64, 10.0),
                    rotation: Rotation::R90,
                    side: if s.refdes == "C1" {
                        Side::Bottom
                    } else {
                        Side::Top
                    },
                    pad_nets,
                    locked: false,
                },
            );
        }
        p.pcb.vias.insert(
            "via_1".into(),
            Via {
                id: "via_1".into(),
                position: Point::mm(1.5, -2.25),
                drill: 300_000,
                diameter: 600_000,
                net: "GND".into(),
                from: CopperLayer::Top,
                to: CopperLayer::Bottom,
            },
        );
        p
    }

    #[test]
    fn ipc_d_356_records_use_the_fixed_columns() {
        let p = board();
        let text = ipc_d_356(&p, "DRAFT");
        assert!(
            validate_ipc_d_356(&text).is_empty(),
            "{:?}",
            validate_ipc_d_356(&text)
        );
        assert!(text.contains("P  UNITS CUST 1\n"));
        assert!(text.contains("C  Status: DRAFT\n"));
        // The long net name gets an alias in the header and in its records.
        assert!(
            text.contains("P  NNAME1     VCC_3V3_MAIN_SUPPLY\n"),
            "{text}"
        );
        let smd: Vec<&str> = text.lines().filter(|l| l.starts_with("327")).collect();
        assert_eq!(smd.len(), 8, "two pads per part:\n{text}");
        let r1 = smd
            .iter()
            .find(|l| l[20..26].trim() == "R1" && l[27..31].trim() == "2")
            .expect("R1 pad 2");
        assert_eq!(&r1[3..17], "GND           ");
        assert_eq!(&r1[26..27], "-");
        assert_eq!(&r1[38..41], "A01");
        assert_eq!(&r1[41..42], "X");
        assert_eq!(&r1[67..71], "R090");
        assert_eq!(&r1[72..74], "S0");
        assert!(smd.iter().any(|l| l[3..17].trim() == "NNAME1"));
        // C1 sits on the bottom: its pads are accessed from the bottom layer.
        let c1 = smd.iter().find(|l| l[20..26].trim() == "C1").expect("C1");
        assert_eq!(&c1[38..41], "A02");
        let via = text
            .lines()
            .find(|l| l.contains("VIA"))
            .expect("via record");
        assert!(via.starts_with("317GND"));
        assert_eq!(&via[32..38], "D0300P");
        assert_eq!(&via[41..57], "X+001500Y-002250");
        assert!(text.ends_with("999\n"));
        assert!(!validate_ipc_d_356("317 short\n").is_empty());
    }

    #[test]
    fn json_netlist_lists_components_nets_and_pads() {
        let p = board();
        let text = json(&p, "DRAFT", "abc");
        let v: serde_json::Value = serde_json::from_str(&text).unwrap();
        assert_eq!(v["format"], "eak-netlist");
        assert_eq!(v["status"], "DRAFT");
        assert_eq!(v["components"].as_array().unwrap().len(), 4);
        assert_eq!(v["components"][0]["refdes"], "C1");
        assert_eq!(v["pcb_pad_nets"].as_array().unwrap().len(), 8);
        assert!(v["nets"].is_array());
    }
}
